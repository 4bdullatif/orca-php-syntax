// Regenerates syntaxes/*.tmLanguage.json from VS Code's grammars at a pinned commit.
// `node scripts/build-grammars.mjs --check` fails when the committed files differ from a fresh build.
import { readFile, writeFile } from 'node:fs/promises'

const VSCODE_COMMIT = '527b5f320f5ed16b68a43ad0248132f1b102c751'
const PHP_TAG = { include: 'text.html.php#php-tag' }
const CAPTURE_KEYS = ['captures', 'beginCaptures', 'endCaptures', 'whileCaptures']

const GRAMMARS = [
  {
    file: 'php-html.tmLanguage.json',
    source: 'extensions/php/syntaxes/html.tmLanguage.json',
    transform: replacePhpInjectionAtRoot,
    note: 'its injections are replaced: #php-tag runs after the HTML rules at the top level'
  },
  {
    file: 'php.tmLanguage.json',
    source: 'extensions/php/syntaxes/php.tmLanguage.json'
  },
  {
    file: 'html.tmLanguage.json',
    source: 'extensions/html/syntaxes/html.tmLanguage.json',
    transform: injectPhpTags,
    note: 'every begin rule and capture tries text.html.php#php-tag first; its injections are removed'
  },
  {
    file: 'html-derivative.tmLanguage.json',
    source: 'extensions/html/syntaxes/html-derivative.tmLanguage.json',
    transform: injectPhpTags,
    note: 'every begin rule and capture tries text.html.php#php-tag first; its injections are removed'
  },
  {
    file: 'javascript.tmLanguage.json',
    source: 'extensions/javascript/syntaxes/JavaScript.tmLanguage.json',
    transform: injectPhpTags,
    note: 'every begin rule and capture tries text.html.php#php-tag first'
  },
  {
    file: 'css.tmLanguage.json',
    source: 'extensions/css/syntaxes/css.tmLanguage.json',
    transform: injectPhpTags,
    note: 'every begin rule and capture tries text.html.php#php-tag first'
  },
  {
    file: 'sql.tmLanguage.json',
    source: 'extensions/sql/syntaxes/sql.tmLanguage.json'
  },
  {
    file: 'json.tmLanguage.json',
    source: 'extensions/json/syntaxes/JSON.tmLanguage.json'
  },
  {
    file: 'xml.tmLanguage.json',
    source: 'extensions/xml/syntaxes/xml.tmLanguage.json',
    transform: dropNonNumericCaptureKeys,
    note: 'capture keys that are not numbers are removed (the engine ignores them, Orca refuses them)'
  }
]

function forEachRule(grammar, visit) {
  const pending = [{ rule: { patterns: grammar.patterns, repository: grammar.repository }, isCapture: false }]
  while (pending.length > 0) {
    const { rule, isCapture } = pending.pop()
    visit(rule, isCapture)
    for (const child of rule.patterns ?? []) {
      pending.push({ rule: child, isCapture: false })
    }
    for (const child of Object.values(rule.repository ?? {})) {
      pending.push({ rule: child, isCapture: false })
    }
    for (const key of CAPTURE_KEYS) {
      for (const child of Object.values(rule[key] ?? {})) {
        pending.push({ rule: child, isCapture: true })
      }
    }
  }
}

// Orca drops grammar `injections`, so VS Code's PHP injection into HTML, CSS and JavaScript is
// reproduced by listing #php-tag first wherever the engine scans: inside begin rules and inside
// captures it re-tokenizes. First in the list matches VS Code's `L:` priority.
function injectPhpTags(grammar) {
  forEachRule(grammar, (rule, isCapture) => {
    const scans = rule.begin !== undefined || (isCapture && rule.patterns !== undefined)
    if (scans) {
      rule.patterns = [{ ...PHP_TAG }, ...(rule.patterns ?? [])]
    }
  })
}

// At the top level VS Code's PHP injection has normal priority, so HTML rules starting at the same
// character (such as `<?xml`) keep it; listing #php-tag after them does the same.
function replacePhpInjectionAtRoot(grammar) {
  grammar.patterns.push({ include: '#php-tag' })
}

function dropNonNumericCaptureKeys(grammar) {
  forEachRule(grammar, (rule) => {
    for (const key of CAPTURE_KEYS) {
      for (const captureKey of Object.keys(rule[key] ?? {})) {
        if (!/^\d+$/.test(captureKey)) {
          delete rule[key][captureKey]
        }
      }
    }
  })
}

async function fetchUpstream(source) {
  const url = `https://raw.githubusercontent.com/microsoft/vscode/${VSCODE_COMMIT}/${source}`
  const response = await fetch(url)
  if (!response.ok) {
    throw new Error(`${url}: HTTP ${response.status}`)
  }
  return response.json()
}

function provenance({ source, note }) {
  const origin = `Generated by scripts/build-grammars.mjs from microsoft/vscode@${VSCODE_COMMIT}:${source}.`
  return note ? `${origin} Modified: ${note}.` : origin
}

async function build(entry) {
  const upstream = await fetchUpstream(entry.source)
  const grammar = {
    comment: provenance(entry),
    name: upstream.name,
    scopeName: upstream.scopeName,
    patterns: upstream.patterns,
    repository: upstream.repository ?? {}
  }
  entry.transform?.(grammar)
  return `${JSON.stringify(grammar, null, '\t')}\n`
}

const check = process.argv.includes('--check')
const stale = []
for (const entry of GRAMMARS) {
  const target = new URL(`../syntaxes/${entry.file}`, import.meta.url)
  const text = await build(entry)
  if (!check) {
    await writeFile(target, text)
    continue
  }
  const committed = await readFile(target, 'utf8').catch(() => null)
  if (committed !== text) {
    stale.push(entry.file)
  }
}
if (stale.length > 0) {
  console.error(`Out of date, run node scripts/build-grammars.mjs: ${stale.join(', ')}`)
  process.exit(1)
}
console.log(check ? 'syntaxes/ matches a fresh build' : `Wrote ${GRAMMARS.length} grammars to syntaxes/`)
